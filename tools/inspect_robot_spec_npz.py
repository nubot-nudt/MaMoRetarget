#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
Inspect a robot_spec.npz generated by export_robot_spec_from_mujoco_xml.py

Usage:
  python tools/inspect_robot_spec_npz.py --npz net/robot_spec_g1.npz
  python inspect_robot_spec_npz.py --npz robot_spec_g1.npz --export_csv joints.csv
  python inspect_robot_spec_npz.py --npz robot_spec_g1.npz --max_show 30 --no_arrays
"""

import argparse
import csv
import math
from typing import Any, Dict, Tuple

import numpy as np


def _is_numeric_array(a: np.ndarray) -> bool:
    return isinstance(a, np.ndarray) and a.dtype.kind in ("i", "u", "f", "b")


def _safe_item(x: Any) -> Any:
    # unwrap scalar arrays / numpy scalars
    if isinstance(x, np.ndarray) and x.shape == ():
        return x.item()
    if isinstance(x, np.generic):
        return x.item()
    return x


def summarize_array(name: str, a: np.ndarray, max_show: int = 10, show_arrays: bool = True) -> None:
    shape = getattr(a, "shape", None)
    dtype = getattr(a, "dtype", None)
    print(f"\n[{name}] shape={shape} dtype={dtype}")

    if not show_arrays:
        return

    if isinstance(a, np.ndarray) and a.dtype == object:
        # often strings
        flat = a.reshape(-1)
        preview = [str(_safe_item(flat[i])) for i in range(min(max_show, flat.size))]
        print(f"  object preview ({len(preview)}/{flat.size}): {preview}")
        return

    if _is_numeric_array(a):
        # handle empty
        if a.size == 0:
            print("  (empty numeric array)")
            return
        # stats
        amin = float(np.nanmin(a))
        amax = float(np.nanmax(a))
        amean = float(np.nanmean(a))
        # for bool, mean is okay as ratio
        print(f"  stats: min={amin:.6g}, mean={amean:.6g}, max={amax:.6g}")
        # preview
        flat = a.reshape(-1)
        preview = flat[: min(max_show, flat.size)]
        print(f"  preview ({preview.size}/{flat.size}): {preview}")
        return

    # other dtypes
    try:
        flat = a.reshape(-1)
        preview = flat[: min(max_show, flat.size)]
        print(f"  preview ({preview.size}/{flat.size}): {preview}")
    except Exception as e:
        print(f"  (cannot preview: {e})")


def check_topology(spec: Dict[str, np.ndarray]) -> Dict[str, Any]:
    """
    Validate parent_idx & edge_index and compute tree stats.
    """
    out: Dict[str, Any] = {}

    joint_names = spec.get("joint_names", None)
    parent_idx = spec.get("parent_idx", None)
    edge_index = spec.get("edge_index", None)

    if joint_names is None or parent_idx is None:
        out["ok"] = False
        out["reason"] = "missing joint_names or parent_idx"
        return out

    Nr = int(joint_names.shape[0])
    out["Nr"] = Nr

    parent_idx = parent_idx.astype(np.int64)
    if parent_idx.shape != (Nr,):
        out["ok"] = False
        out["reason"] = f"parent_idx has wrong shape {parent_idx.shape}, expected ({Nr},)"
        return out

    # parent range check
    bad = np.where((parent_idx >= Nr) | (parent_idx < -1))[0]
    out["bad_parent_indices"] = bad.tolist()

    roots = np.where(parent_idx < 0)[0]
    out["roots"] = roots.tolist()
    out["n_roots"] = int(roots.size)

    # build children list
    children = [[] for _ in range(Nr)]
    for i, p in enumerate(parent_idx.tolist()):
        if p >= 0:
            children[p].append(i)
    out["max_children"] = int(max((len(c) for c in children), default=0))
    out["n_leaf"] = int(sum(1 for c in children if len(c) == 0))

    # depth (for a forest, take roots as depth 0)
    depth = np.full((Nr,), -1, dtype=np.int32)
    stack = [(int(r), 0) for r in roots.tolist()]
    for r in roots.tolist():
        depth[r] = 0

    # iterative DFS from each root
    while stack:
        node, d = stack.pop()
        for ch in children[node]:
            depth[ch] = d + 1
            stack.append((ch, d + 1))

    out["unreached_nodes"] = np.where(depth < 0)[0].tolist()
    out["max_depth"] = int(depth.max()) if depth.size else 0

    # edge_index sanity
    if edge_index is not None:
        ei = np.asarray(edge_index)
        if ei.ndim == 2 and ei.shape[0] == 2:
            E = int(ei.shape[1])
            out["E"] = E
            # check each edge corresponds to parent_idx
            mism = []
            for k in range(E):
                p = int(ei[0, k])
                c = int(ei[1, k])
                if c < 0 or c >= Nr:
                    mism.append((k, "child_oob", p, c))
                elif parent_idx[c] != p:
                    mism.append((k, "parent_mismatch", p, c))
            out["edge_mismatches_first20"] = mism[:20]
        else:
            out["edge_index_issue"] = f"edge_index shape {ei.shape} not (2,E)"

    out["ok"] = (len(out["bad_parent_indices"]) == 0) and (len(out["unreached_nodes"]) == 0)
    return out


def export_joints_csv(spec: Dict[str, np.ndarray], path: str) -> None:
    joint_names = spec["joint_names"]
    body_names = spec.get("body_names", None)
    parent_idx = spec["parent_idx"].astype(np.int64)
    axis_local = spec.get("axis_local", None)
    joint_type = spec.get("joint_type", None)
    q_min = spec.get("q_min", None)
    q_max = spec.get("q_max", None)
    limited = spec.get("limited", None)
    rest_q = spec.get("rest_q", None)
    offset_len = spec.get("offset_len", None)

    Nr = int(joint_names.shape[0])

    def jname(i: int) -> str:
        return str(_safe_item(joint_names[i]))

    def bname(i: int) -> str:
        if body_names is None:
            return ""
        return str(_safe_item(body_names[i]))

    def pname(i: int) -> str:
        p = int(parent_idx[i])
        return "" if p < 0 else jname(p)

    def jtype_str(i: int) -> str:
        if joint_type is None:
            return ""
        t = int(joint_type[i])
        return {0: "hinge", 1: "slide"}.get(t, str(t))

    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow([
            "idx", "joint_name", "body_name", "parent_idx", "parent_name",
            "joint_type", "axis_x", "axis_y", "axis_z",
            "limited", "q_min", "q_max", "rest_q", "offset_len"
        ])
        for i in range(Nr):
            ax = axis_local[i] if axis_local is not None else [np.nan, np.nan, np.nan]
            w.writerow([
                i, jname(i), bname(i), int(parent_idx[i]), pname(i),
                jtype_str(i),
                float(ax[0]), float(ax[1]), float(ax[2]),
                int(limited[i]) if limited is not None else "",
                float(q_min[i]) if q_min is not None else "",
                float(q_max[i]) if q_max is not None else "",
                float(rest_q[i]) if rest_q is not None else "",
                float(offset_len[i]) if offset_len is not None else "",
            ])
    print(f"\n[export] joints csv saved to: {path}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--npz", type=str, required=True, help="Path to robot_spec*.npz")
    ap.add_argument("--max_show", type=int, default=30, help="Max preview items per array")
    ap.add_argument("--no_arrays", action="store_true", help="Only print keys/shape/dtype, no previews/stats")
    ap.add_argument("--export_csv", type=str, default="", help="Export joints table csv to this path")
    args = ap.parse_args()

    # IMPORTANT: allow_pickle=True because joint_names/body_names/base_body_name are dtype=object
    data = np.load(args.npz, allow_pickle=True)

    keys = sorted(list(data.keys()))
    print(f"[npz] {args.npz}")
    print(f"[npz] keys ({len(keys)}): {keys}")

    spec: Dict[str, np.ndarray] = {k: data[k] for k in keys}

    # high-level header
    if "base_body_name" in spec:
        print(f"\n[base_body_name] {str(_safe_item(spec['base_body_name']))}")
    if "base_has_freejoint" in spec:
        print(f"[base_has_freejoint] {int(np.asarray(spec['base_has_freejoint']).reshape(-1)[0])}")
    if "joint_names" in spec:
        Nr = int(spec["joint_names"].shape[0])
        print(f"[Nr joints] {Nr}")
        print("[first joints]", [str(_safe_item(spec["joint_names"][i])) for i in range(min(30, Nr))])

    # per-key summaries
    for k in keys:
        a = spec[k]
        summarize_array(k, a, max_show=args.max_show, show_arrays=(not args.no_arrays))

    # topology checks
    topo = check_topology(spec)
    print("\n[Topology check]")
    for kk, vv in topo.items():
        print(f"  {kk}: {vv}")

    # export csv if needed
    if args.export_csv:
        export_joints_csv(spec, args.export_csv)


if __name__ == "__main__":
    main()
